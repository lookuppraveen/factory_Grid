import 'reflect-metadata';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import * as yaml from 'js-yaml';
import { buildOpenApi, createApp } from '../bootstrap';

/**
 * Writes the API's OpenAPI document to contracts/factorygrid-api.yaml.
 * CI runs this and fails if the committed contract differs (pnpm contracts:check).
 */
async function main(): Promise<void> {
  // The document is built without serving requests, so placeholders are enough.
  process.env.DATABASE_URL ??= 'postgresql://unused:unused@localhost:5432/unused';
  process.env.JWT_SECRET ??= 'openapi-export-placeholder-secret-not-used-for-signing';

  const app = await createApp({ logger: false });
  await app.init();
  const document = buildOpenApi(app);
  await app.close();

  const target = resolve(__dirname, '../../../../../contracts/factorygrid-api.yaml');
  const header = '# Generated by `pnpm --filter factorygrid-api openapi:export`. Do not edit by hand.\n';
  writeFileSync(target, header + yaml.dump(document, { noRefs: true, lineWidth: 120, sortKeys: false }));
  console.log(`OpenAPI contract written to ${target}`);
}

void main();
